function EEG = load_prepare_eeg(filepath, target_srate, nonEEGLabels, lookupFile)
    [fdir, fname, ext] = fileparts(filepath);
    EEG = pop_loadset('filename', [fname ext], 'filepath', fdir);
    EEG = eeg_checkset(EEG, 'eventconsistency');

    if abs(EEG.srate - target_srate) > 1e-6
        EEG = pop_resample(EEG, target_srate);
        EEG = eeg_checkset(EEG, 'eventconsistency');
    end

    EEG = remove_noneeg_channels(EEG, nonEEGLabels);
    EEG = pop_chanedit(EEG, 'lookup', lookupFile);

    % Average reference across EEG channels; channels are not spatially averaged.
    EEG = pop_reref(EEG, []);
    EEG = eeg_checkset(EEG, 'eventconsistency');
end

function EEG = remove_noneeg_channels(EEG, nonEEGLabels)
    labels = string({EEG.chanlocs.labels});
    isNonEEG = false(size(labels));
    for i = 1:numel(nonEEGLabels)
        isNonEEG = isNonEEG | strcmpi(labels, nonEEGLabels{i});
    end

    % Also retain only E<number> channels.
    isEGI = false(size(labels));
    for ch = 1:numel(labels)
        isEGI(ch) = ~isempty(regexp(upper(labels(ch)), '^E\d+$', 'once'));
    end

    keep = ~isNonEEG & isEGI;
    EEG = pop_select(EEG, 'channel', find(keep));
    EEG = eeg_checkset(EEG);
end

function [labels, loc] = select_expected_channels(EEG, expected_labels)
    eegLabels = upper(string({EEG.chanlocs.labels}));
    [tf, loc] = ismember(upper(string(expected_labels)), eegLabels);
    labels = expected_labels(tf);
    loc = loc(tf);
end

function values = compute_alpha_all_channels(X, srate, alpha_band, use_log10_power)
    % X: channel x samples. Returns one alpha value per channel.
    nChan = size(X,1);
    nSamp = size(X,2);
    values = nan(nChan,1);

    win = hamming(nSamp);
    nfft = max(512, 2^nextpow2(nSamp));

    for ch = 1:nChan
        sig = double(X(ch,:));
        sig = sig - mean(sig, 'omitnan');
        sig = detrend(sig);

        if all(~isfinite(sig)) || std(sig, 'omitnan') == 0
            continue;
        end

        [pxx, f] = pwelch(sig, win, 0, nfft, srate);
        freq_idx = f >= alpha_band(1) & f <= alpha_band(2);
        if ~any(freq_idx)
            continue;
        end

        v = mean(pxx(freq_idx), 'omitnan');
        if use_log10_power
            v = log10(max(v, realmin));
        end
        values(ch) = v;
    end
end

function latencies = get_event_latencies(EEG, target_type, allow_prefix)
    % Exact matching is used for triggers. For VOFF, allow labels such as
    % VOFF, VOFF_1, or VOFF_trialXX by setting allow_prefix=true.
    if nargin < 3
        allow_prefix = false;
    end

    latencies = [];
    target = canonical_event_type(target_type);
    for e = 1:numel(EEG.event)
        this_type = canonical_event_type(EEG.event(e).type);
        if (~allow_prefix && strcmp(this_type, target)) || ...
                (allow_prefix && startsWith(this_type, target))
            latencies(end+1,1) = double(EEG.event(e).latency); %#ok<AGROW>
        end
    end
end

function blocks = define_training_blocks(s111_lat, s88_lat, trials_per_block)
    blocks = {[], [], []};
    s111_lat = sort(s111_lat(:));
    s88_lat = sort(s88_lat(:));

    if isempty(s111_lat)
        return;
    end

    % Identify starts of S88 test runs. A new run starts when at least one
    % S111 occurred after the preceding S88 event.
    test_run_starts = [];
    if ~isempty(s88_lat)
        test_run_starts = s88_lat(1);
        for i = 2:numel(s88_lat)
            had_s111_between = any(s111_lat > s88_lat(i-1) & s111_lat < s88_lat(i));
            if had_s111_between
                test_run_starts(end+1,1) = s88_lat(i); %#ok<AGROW>
            end
        end
    end

    if numel(test_run_starts) >= 1
        candidates = s111_lat(s111_lat < test_run_starts(1));
        blocks{1} = take_last_n(candidates, trials_per_block);
    else
        blocks{1} = take_first_n(s111_lat, trials_per_block);
    end

    if numel(test_run_starts) >= 2
        candidates = s111_lat(s111_lat < test_run_starts(2));
        blocks{2} = take_last_n(candidates, trials_per_block);
    elseif numel(s111_lat) >= 2*trials_per_block
        blocks{2} = s111_lat(trials_per_block+1:min(2*trials_per_block,numel(s111_lat)));
    end

    blocks{3} = take_last_n(s111_lat, trials_per_block);

    % Remove accidental overlap between B1/B2/B3 if the event structure is incomplete.
    if ~isempty(blocks{1}) && ~isempty(blocks{2})
        blocks{2} = setdiff(blocks{2}, blocks{1}, 'stable');
    end
    if ~isempty(blocks{3})
        blocks{3} = setdiff(blocks{3}, [blocks{1}; blocks{2}], 'stable');
        if numel(blocks{3}) < trials_per_block
            blocks{3} = take_last_n(s111_lat, trials_per_block);
        end
    end
end

function x = take_last_n(x, n)
    x = x(:);
    if numel(x) > n
        x = x(end-n+1:end);
    end
end

function x = take_first_n(x, n)
    x = x(:);
    if numel(x) > n
        x = x(1:n);
    end
end

function T = append_subject_condition_rows(T, sid, condition, labels, values, nEpochs)
    n = numel(labels);
    tmp = table();
    tmp.SubjectID = repmat(sid, n, 1);
    tmp.Condition = repmat(string(condition), n, 1);
    tmp.Channel = string(labels(:));
    tmp.AlphaPower = values(:);
    tmp.N_EpochsOrTrials = repmat(nEpochs, n, 1);
    T = [T; tmp];
end

function s = canonical_event_type(x)
    if ischar(x) || isstring(x)
        s = char(x);
    elseif isnumeric(x)
        s = num2str(x);
    else
        s = '';
    end
    s = upper(regexprep(strtrim(s), '\s+', ''));
end

function sid = parse_subject_id(filename)
    % First try the reference-script convention: characters 3-4.
    sid = NaN;
    if numel(filename) >= 4
        candidate = str2double(filename(3:4));
        if isfinite(candidate)
            sid = candidate;
            return;
        end
    end

    % General fallback: first integer in the filename.
    tok = regexp(filename, '\d+', 'match', 'once');
    if ~isempty(tok)
        sid = str2double(tok);
    end
end

function y = mean_omitnan(x)
    y = mean(x, 'omitnan');
end

function y = std_omitnan(x)
    y = std(x, 'omitnan');
end
