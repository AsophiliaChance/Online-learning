    chanlocs128(ch) = lookupLocs(idx);
end

roi_idx = find(ismember(upper(string(expected_labels)), upper(string(alpha_roi))));

%% ---------------- ONE TOPOGRAPHY FIGURE ----------------
finite_values = map_vector(isfinite(map_vector));
