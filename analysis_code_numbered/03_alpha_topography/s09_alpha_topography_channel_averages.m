%% ============================================================
% Condition- and subject-averaged alpha-power topography
%
% Averaging hierarchy (electrodes are NEVER averaged together):
%   1) For each subject, condition, and electrode, calculate alpha power for
%      every usable epoch/trial.
%   2) Average epochs/trials within Subject x Condition x Electrode.
%      Resulting data dimension: subject x condition x channel.
%   3) Average Rest, B1, B2, and B3 within each subject for every electrode.
%      Resulting data dimension: subject x channel.
%   4) Average across subjects separately for every electrode.
%      Resulting topography dimension: channel.
%
% Electrodes are NEVER averaged together.
%
% REST:
%   - First two S111 markers
%   - S111 + 10 s to S111 + 100 s
%   - Non-overlapping 2-s epochs
%
% TRAINING:
%   - Block 1: last 63 S111 trials before the first S88 test run
%   - Block 2: last 63 S111 trials before the second S88 test run
%   - Block 3: last 63 S111 trials in the recording
%   - Load *_with_vocal_events.set files generated by the ACC script
%   - For each selected S111, use the first VOFF before the next S111
%   - Analysis window: VOFF + 0.3 to + 2.3 s
%
% TOPOGRAPHY:
%   - EGI HydroCel 128 electrodes, using the supplied 129-channel lookup file
%   - No electrode names
%   - Only ROI electrodes are marked
%   - One scalp map averaged across Rest/B1/B2/B3 and subjects
%   - 600-dpi TIFF output
%   - Only one channel-level CSV is saved
%% ============================================================

clear; clc;

%% ---------------- PATHS ----------------
dir_rest  = 'D:\online_learning\resting_state';
dir_train = 'D:\online_learning\training_psychophysiology';
restFilePattern  = '*_ica_clean.set';
trainFilePattern = '*_with_vocal_events.set';

outDir = 'D:\online_learning\spectral_theta_alpha\alpha_topography_condition_subject_average';
if ~exist(outDir, 'dir'), mkdir(outDir); end

% Channel-location lookup copied from the supplied reference script.
lookupFile = ['S:\Program\matlab2019toolbox\eeglab_current\eeglab2024.0\', ...
              'plugins\dipfit\standard_BESA\GSN-HydroCel-129.sfp'];

outTif = fullfile(outDir, 'alpha_topography_condition_subject_average_600dpi.tif');
outAverageCsv = fullfile(outDir, 'alpha_condition_subject_average_channel.csv');

% Do not save subject-level, condition-level, or MAT outputs.
legacyFiles = { ...
    fullfile(outDir, 'alpha_subject_condition_channel.csv'), ...
    fullfile(outDir, 'alpha_grand_average_condition_channel.csv'), ...
    fullfile(outDir, 'alpha_topography_subject_condition_grand_average.mat')};
for iLegacy = 1:numel(legacyFiles)
    if exist(legacyFiles{iLegacy}, 'file'), delete(legacyFiles{iLegacy}); end
end

%% ---------------- SETTINGS ----------------
alpha_band = [8 12];
target_srate = 250;
use_log10_power = true;

% Use only participants who have valid Rest, B1, B2, and B3 maps.
require_complete_subjects = true;

% EGI 128 electrodes used for the topography.
expected_labels = arrayfun(@(x)sprintf('E%d',x), 1:128, 'UniformOutput', false);

% Posterior ROI: mark only these electrodes.
alpha_roi = {'E70','E71','E72','E75','E76','E77','E67','E83'};

% Auxiliary/non-EEG channels
nonEEGLabels = {'ECG','EDA','ACCx','ACCy','ACCz','EACCx','EACCy','EACCz'};

% REST settings
rest_trigger = 'S111';
use_first_n_rest_triggers = 2;
rest_start_sec = 10;
rest_end_sec = 100;
rest_epoch_sec = 2.0;

% TRAINING settings
training_trigger = 'S111';
test_trigger = 'S88';
voff_event = 'VOFF';
trials_per_block = 63;
voff_window_sec = [0.3 2.3];

% Figure style
font_name = 'Times New Roman';
font_size = 12;
title_font_size = 14;
fig_width_cm = 10.5;
fig_height_cm = 9.5;
roi_marker_size = 6;
condition_order = {'Rest','B1','B2','B3'};
colorbar_label = '\alpha power (log_{10}(\muV^2/Hz))';

%% ---------------- START EEGLAB ----------------
assert(exist(lookupFile, 'file') == 2, ...
    'Cannot find channel-location file:\n%s', lookupFile);

if isempty(which('eeglab'))
    error('EEGLAB is not on the MATLAB path.');
end

eeglab; close(gcf);

%% ---------------- FILE DISCOVERY ----------------
files_rest = dir(fullfile(dir_rest, restFilePattern));
files_train = dir(fullfile(dir_train, trainFilePattern));

if isempty(files_rest)
    error('No resting-state files found with pattern %s in %s.', restFilePattern, dir_rest);
end
if isempty(files_train)
    error(['No training files containing VOFF events were found with pattern %s in %s.\n', ...
        'Run the ACC vocal-event detection script first.'], trainFilePattern, dir_train);
end

fprintf('Found %d REST files and %d TRAIN files.\n', ...
    numel(files_rest), numel(files_train));

%% ============================================================
% REST: subject x condition x channel
%% ============================================================
REST_ROWS = table();

for f = 1:numel(files_rest)
    filename = files_rest(f).name;
    filepath = fullfile(files_rest(f).folder, filename);
    sid = parse_subject_id(filename);

    if isnan(sid)
        warning('Cannot parse subject ID from REST file: %s. Skip.', filename);
        continue;
    end

    fprintf('\n[REST] Subject %d: %s\n', sid, filename);

    try
        EEG = load_prepare_eeg(filepath, target_srate, nonEEGLabels, lookupFile);
        [labels, loc] = select_expected_channels(EEG, expected_labels);

        if isempty(loc)
            warning('No EGI channels found in %s. Skip.', filename);
            continue;
        end

        rest_latencies = get_event_latencies(EEG, rest_trigger);
        if isempty(rest_latencies)
            warning('No %s events in %s. Skip.', rest_trigger, filename);
            continue;
        end

        rest_latencies = sort(rest_latencies(:));
        rest_latencies = rest_latencies(1:min(use_first_n_rest_triggers, numel(rest_latencies)));

        epoch_values = [];  % channel x epoch
        epoch_len = round(rest_epoch_sec * EEG.srate);

        for r = 1:numel(rest_latencies)
            seg_start = round(rest_latencies(r) + rest_start_sec * EEG.srate);
            seg_end   = round(rest_latencies(r) + rest_end_sec * EEG.srate) - 1;
            seg_start = max(1, seg_start);
            seg_end   = min(EEG.pnts, seg_end);

            if seg_end - seg_start + 1 < epoch_len
                continue;
            end

            ep_starts = seg_start:epoch_len:(seg_end - epoch_len + 1);
            for e = 1:numel(ep_starts)
                idx = ep_starts(e):(ep_starts(e)+epoch_len-1);
                X = double(EEG.data(loc, idx));
                epoch_values(:, end+1) = compute_alpha_all_channels( ...
                    X, EEG.srate, alpha_band, use_log10_power); %#ok<AGROW>
            end
        end

        if isempty(epoch_values)
            warning('No usable resting epochs for subject %d.', sid);
            continue;
        end

        % Average epochs within Subject x Rest x Electrode.
        subj_chan_mean = mean(epoch_values, 2, 'omitnan');
        REST_ROWS = append_subject_condition_rows( ...
            REST_ROWS, sid, "Rest", labels, subj_chan_mean, size(epoch_values,2));

    catch ME
        warning('REST failed for %s: %s', filename, ME.message);
    end
end

%% ============================================================
% TRAINING: subject x block x channel
%% ============================================================
TRAIN_ROWS = table();

for f = 1:numel(files_train)
    filename = files_train(f).name;
    filepath = fullfile(files_train(f).folder, filename);
    sid = parse_subject_id(filename);

    if isnan(sid)
        warning('Cannot parse subject ID from TRAIN file: %s. Skip.', filename);
        continue;
    end

    fprintf('\n[TRAIN] Subject %d: %s\n', sid, filename);

    try
        EEG = load_prepare_eeg(filepath, target_srate, nonEEGLabels, lookupFile);
        [labels, loc] = select_expected_channels(EEG, expected_labels);

        if isempty(loc)
            warning('No EGI channels found in %s. Skip.', filename);
            continue;
        end

        s111_lat = sort(get_event_latencies(EEG, training_trigger));
        s88_lat  = sort(get_event_latencies(EEG, test_trigger));
        voff_lat = sort(get_event_latencies(EEG, voff_event, true));

        if isempty(s111_lat)
            warning('No %s events in %s. Skip.', training_trigger, filename);
            continue;
        end
        if isempty(voff_lat)
            warning(['No %s events in %s. This file is not usable for the VOFF-locked ', ...
                'topography. Confirm that it was generated by the ACC vocal-event script.'], ...
                voff_event, filename);
            continue;
        end

        fprintf('Found %d S111, %d S88, and %d VOFF events.\n', ...
            numel(s111_lat), numel(s88_lat), numel(voff_lat));

        block_trial_lats = define_training_blocks( ...
            s111_lat, s88_lat, trials_per_block);

        for b = 1:3
            trial_lats = block_trial_lats{b};
            if isempty(trial_lats)
                warning('Subject %d has no trials for B%d.', sid, b);
                continue;
            end

            trial_values = [];  % channel x usable trial

            for t = 1:numel(trial_lats)
                this_s111 = trial_lats(t);

                % Search until the next S111; for the final S111 use recording end.
                next_candidates = s111_lat(s111_lat > this_s111);
                if isempty(next_candidates)
                    next_s111 = EEG.pnts + 1;
                else
                    next_s111 = next_candidates(1);
                end

                candidates = voff_lat(voff_lat > this_s111 & voff_lat < next_s111);
                if isempty(candidates)
                    continue;
                end
                this_voff = candidates(1);

                win_start = round(this_voff + voff_window_sec(1) * EEG.srate);
                win_end   = round(this_voff + voff_window_sec(2) * EEG.srate) - 1;

                if win_start < 1 || win_end > EEG.pnts || win_end <= win_start
                    continue;
                end

                X = double(EEG.data(loc, win_start:win_end));
                trial_values(:, end+1) = compute_alpha_all_channels( ...
                    X, EEG.srate, alpha_band, use_log10_power); %#ok<AGROW>
            end

            if isempty(trial_values)
                warning('Subject %d B%d has no usable VOFF epochs.', sid, b);
                continue;
            end

            % Average trials within Subject x Block x Electrode.
            subj_chan_mean = mean(trial_values, 2, 'omitnan');
            TRAIN_ROWS = append_subject_condition_rows( ...
                TRAIN_ROWS, sid, "B" + string(b), labels, ...
                subj_chan_mean, size(trial_values,2));
        end

    catch ME
        warning('TRAIN failed for %s: %s', filename, ME.message);
    end
end

%% ---------------- COMBINE SUBJECT-LEVEL MAPS ----------------
SUBJECT_DATA = [REST_ROWS; TRAIN_ROWS];
if isempty(SUBJECT_DATA)
    error('No subject-level condition-by-channel alpha data were generated.');
end

SUBJECT_DATA.Condition = categorical( ...
    string(SUBJECT_DATA.Condition), condition_order, 'Ordinal', true);
SUBJECT_DATA = SUBJECT_DATA(~isundefined(SUBJECT_DATA.Condition), :);

% Retain only subjects with valid Rest, B1, B2, and B3 maps so that all
% four conditions contribute equally to every subject-level average.
subjects = unique(SUBJECT_DATA.SubjectID);
complete_subjects = [];
for i = 1:numel(subjects)
    sid = subjects(i);
    conds = unique(string(SUBJECT_DATA.Condition(SUBJECT_DATA.SubjectID == sid)));
    if all(ismember(string(condition_order), conds))
        complete_subjects(end+1,1) = sid; %#ok<AGROW>
    end
end

SUBJECT_DATA = SUBJECT_DATA(ismember(SUBJECT_DATA.SubjectID, complete_subjects), :);
fprintf('\nComplete subjects retained: %d\n', numel(complete_subjects));

if isempty(SUBJECT_DATA)
    error('No subjects remain after complete-condition filtering.');
end

%% ---------------- AVERAGE CONDITIONS WITHIN SUBJECT ----------------
% For each subject and electrode, average Rest, B1, B2, and B3.
% Channels remain separate; there is no spatial/electrode averaging.
[Gsub, subj_col, chan_col] = findgroups( ...
    SUBJECT_DATA.SubjectID, string(SUBJECT_DATA.Channel));

subj_condition_mean = splitapply(@mean_omitnan, SUBJECT_DATA.AlphaPower, Gsub);
subj_condition_n = splitapply(@numel, SUBJECT_DATA.AlphaPower, Gsub);

SUBJECT_CONDITION_AVG = table();
SUBJECT_CONDITION_AVG.SubjectID = subj_col;
SUBJECT_CONDITION_AVG.Channel = chan_col;
SUBJECT_CONDITION_AVG.AlphaPower = subj_condition_mean;
SUBJECT_CONDITION_AVG.NConditions = subj_condition_n;

% Keep rows in which all four conditions contributed.
SUBJECT_CONDITION_AVG = SUBJECT_CONDITION_AVG( ...
    SUBJECT_CONDITION_AVG.NConditions == numel(condition_order) & ...
    isfinite(SUBJECT_CONDITION_AVG.AlphaPower), :);

if isempty(SUBJECT_CONDITION_AVG)
    error('No valid subject x channel averages remain after condition averaging.');
end

%% ---------------- GRAND AVERAGE ACROSS SUBJECTS ----------------
% Average the condition-averaged subject maps across subjects, separately
% for every electrode.
[Gchan, channel_col] = findgroups(string(SUBJECT_CONDITION_AVG.Channel));
mean_alpha = splitapply(@mean_omitnan, SUBJECT_CONDITION_AVG.AlphaPower, Gchan);
sd_alpha   = splitapply(@std_omitnan,  SUBJECT_CONDITION_AVG.AlphaPower, Gchan);
n_subjects = splitapply(@numel, SUBJECT_CONDITION_AVG.AlphaPower, Gchan);
sem_alpha  = sd_alpha ./ sqrt(n_subjects);

AVERAGE = table();
AVERAGE.Channel = channel_col;
AVERAGE.MeanAlphaPower = mean_alpha;
AVERAGE.SD = sd_alpha;
AVERAGE.SEM = sem_alpha;
AVERAGE.NSubjects = n_subjects;
AVERAGE.NConditionsPerSubject = repmat(numel(condition_order), height(AVERAGE), 1);

% Save only this condition- and subject-averaged channel table.
writetable(AVERAGE, outAverageCsv);

%% ---------------- BUILD ONE CHANNEL VECTOR ----------------
nChan = numel(expected_labels);
map_vector = nan(nChan, 1);
n_vector = nan(nChan, 1);

for ch = 1:nChan
    idx = strcmpi(AVERAGE.Channel, expected_labels{ch});
    if any(idx)
        k = find(idx, 1, 'first');
        map_vector(ch) = AVERAGE.MeanAlphaPower(k);
        n_vector(ch) = AVERAGE.NSubjects(k);
    end
end

%% ---------------- CHANNEL LOCATIONS ----------------
lookupLocs = readlocs(lookupFile);
lookupLabels = upper(string({lookupLocs.labels}));

chanlocs128 = repmat(lookupLocs(1), 1, nChan);
for ch = 1:nChan
    idx = find(strcmpi(lookupLabels, expected_labels{ch}), 1);
