%% Compute posterior alpha power from VOFF-locked EEG segments
% Steps:
%   1) Load EEGLAB .set files that already contain VON/VOFF events.
%   2) Resample temporarily to 250 Hz.
%   3) Apply average reference using EEG channels only.
%      Auxiliary channels ECG/EDA/ACCx/ACCy/ACCz are retained in the dataset
%      but excluded from rereferencing and alpha-power calculation.
%   4) Extract each VOFF + 0.3 to 2.3 s segment.
%   5) Compute alpha power, 8-12 Hz, over a posterior ROI.
%   6) Save trial-level and block-level CSV files.
%
% Recommended input:
%   *_with_vocal_events.set generated by the ACC vocal-onset script.
%
% Output:
%   alpha_VOFF_trial_level_0p3_2p3.csv
%   alpha_VOFF_block_level_0p3_2p3.csv
%   alpha_VOFF_channel_level_0p3_2p3.csv
%
% Notes:
%   - The script does NOT overwrite the original .set files.
%   - By default, it does NOT save the resampled/rereferenced .set files.
%   - If save_preprocessed_set = true, it saves a copy with suffix
%     *_alpha250_avgref.set.

clear; clc;

%% ===================== User settings =====================
datadir = 'D:\online_learning\training_psychophysiology';
filt    = '*_with_vocal_events.set';

% Event and segment settings
voff_event = 'VOFF';
seg_start_sec = 0.30;   % relative to VOFF
seg_end_sec   = 2.30;   % relative to VOFF

% Resampling
target_srate = 250;

% Alpha settings
alpha_band = [8 12];
use_log10_power = true;

% Posterior alpha ROI; adjust if needed.
alpha_roi = {'E70','E71','E72','E75','E76','E77','E67','E83'};

% Auxiliary channels to retain but exclude from EEG analysis/rereference
aux_labels = {'ECG','EDA','ACCx','ACCy','ACCz','EACCx','EACCy','EACCz'};

% Block assignment based on trial order
trials_per_block = 63;

% PSD settings for a 2-s VOFF segment
% Use one Hamming-tapered window spanning the full segment.
% With 2 s at 250 Hz, frequency resolution is 0.5 Hz before zero padding.
welch_window_sec = [];   % [] = full segment length
welch_overlap_frac = 0;  % if full segment, overlap is 0
nfft_min = 512;          % minimum nfft; actual nfft = max(nfft_min, 2^nextpow2(segment length))

% Optional output of resampled/rereferenced .set copy
save_preprocessed_set = false;
preprocessed_suffix = '_alpha250_avgref.set';

% Output files
out_trial_csv   = fullfile(datadir, 'alpha_VOFF_trial_level_0p3_2p3.csv');
out_block_csv   = fullfile(datadir, 'alpha_VOFF_block_level_0p3_2p3.csv');
out_channel_csv = fullfile(datadir, 'alpha_VOFF_channel_level_0p3_2p3.csv');

%% ===================== Start EEGLAB =====================
eeglab; close(gcf);

files = dir(fullfile(datadir, filt));
if isempty(files)
    error('No files found: %s', fullfile(datadir, filt));
end

TRIAL_ALL = table();
CHAN_ALL  = table();

%% ===================== File loop =====================
for curfile = 1:numel(files)

    filename = files(curfile).name;
    [~, nam, ~] = fileparts(filename);

    fprintf('\n==============================\n');
    fprintf('Processing %s\n', filename);
    fprintf('==============================\n');

    EEG = pop_loadset('filename', filename, 'filepath', datadir);
    EEG = eeg_checkset(EEG, 'eventconsistency');

    %% ----------------------------------------------------------
    % 1) Resample to 250 Hz
    %% ----------------------------------------------------------
    if abs(EEG.srate - target_srate) > 1e-6
        fprintf('Resampling from %.3f Hz to %.3f Hz...\n', EEG.srate, target_srate);
        EEG = pop_resample(EEG, target_srate);
        EEG = eeg_checkset(EEG, 'eventconsistency');
    else
        fprintf('Sampling rate already %.3f Hz. Skip resampling.\n', EEG.srate);
    end

    fs = EEG.srate;

    %% ----------------------------------------------------------
    % 2) Identify EEG channels and exclude auxiliary channels
    %% ----------------------------------------------------------
    raw_labels = {EEG.chanlocs.labels};
    canon_labels = cellfun(@canonical_label, raw_labels, 'UniformOutput', false);
    canon_aux = cellfun(@canonical_label, aux_labels, 'UniformOutput', false);

    is_aux = ismember(canon_labels, canon_aux);
    eeg_idx = find(~is_aux);

    if isempty(eeg_idx)
        warning('No EEG channels left after excluding auxiliary channels in %s. Skip.', filename);
        continue;
    end

    fprintf('EEG channels used for average reference and alpha analysis: %d\n', numel(eeg_idx));
    fprintf('Auxiliary channels retained but excluded: ');
    disp(raw_labels(is_aux));

    %% ----------------------------------------------------------
    % 3) Average reference using EEG channels only
    %% ----------------------------------------------------------
    eeg_data = double(EEG.data(eeg_idx, :));
    avg_ref = mean(eeg_data, 1);
    EEG.data(eeg_idx, :) = eeg_data - avg_ref;
    EEG = eeg_checkset(EEG);

    %% ----------------------------------------------------------
    % 4) Identify posterior alpha ROI channels
    %% ----------------------------------------------------------
    canon_roi = cellfun(@canonical_label, alpha_roi, 'UniformOutput', false);
    roi_idx = find(ismember(canon_labels, canon_roi) & ~is_aux);

    if isempty(roi_idx)
        warning('No posterior alpha ROI channels found in %s. Skip.', filename);
        continue;
    end

    fprintf('Posterior alpha ROI channels found (%d): %s\n', ...
        numel(roi_idx), strjoin(raw_labels(roi_idx), ', '));

    %% Optional save of resampled/rereferenced copy
    if save_preprocessed_set
        pop_saveset(EEG, 'filename', [nam preprocessed_suffix], 'filepath', datadir);
    end

    %% ----------------------------------------------------------
    % 5) Find VOFF events
    %% ----------------------------------------------------------
    ev_type = cell(numel(EEG.event), 1);
    for e = 1:numel(EEG.event)
        ev_type{e} = canonical_event_type(EEG.event(e).type);
    end

    voff_clean = canonical_event_type(voff_event);
    idx_voff = find(strcmp(ev_type, voff_clean));

    if isempty(idx_voff)
        warning('No %s events found in %s. Skip.', voff_event, filename);
        continue;
    end

    voff_lat = [EEG.event(idx_voff).latency];
    voff_lat = round(voff_lat(:));
    fprintf('Found %d %s events.\n', numel(voff_lat), voff_event);

    %% ----------------------------------------------------------
    % 6) Extract VOFF+0.3-2.3 s segments and compute alpha power
    %% ----------------------------------------------------------
    seg_start_samp_offset = round(seg_start_sec * fs);
    seg_end_samp_offset   = round(seg_end_sec   * fs) - 1;  % keep exact duration close to 2.0 s

    subject_trial_rows = table();
    subject_chan_rows  = table();

    for tr = 1:numel(voff_lat)

        lat = voff_lat(tr);
        seg_start = lat + seg_start_samp_offset;
        seg_end   = lat + seg_end_samp_offset;

        block_id = ceil(tr / trials_per_block);

        if seg_start < 1 || seg_end > EEG.pnts || seg_end <= seg_start
            trial_usable = false;
            reject_reason = "segment_out_of_range";
            roi_alpha = NaN;
            roi_alpha_raw = NaN;
            n_roi_chan_used = 0;
        else
            trial_usable = true;
            reject_reason = "usable";

            seg = double(EEG.data(roi_idx, seg_start:seg_end));

            [alpha_by_chan_raw, alpha_by_chan_out] = compute_alpha_for_channels( ...
                seg, fs, alpha_band, use_log10_power, welch_window_sec, ...
                welch_overlap_frac, nfft_min);

            roi_alpha_raw = mean(alpha_by_chan_raw, 'omitnan');
            roi_alpha = mean(alpha_by_chan_out, 'omitnan');
            n_roi_chan_used = sum(isfinite(alpha_by_chan_out));

            % Save channel-level rows
            for c = 1:numel(roi_idx)
                tmpc = table();
                tmpc.File = string(filename);
                tmpc.Subject = string(nam);
                tmpc.Trial = tr;
                tmpc.Block = block_id;
                tmpc.EventType = string(voff_event);
                tmpc.VOFF_latency_sample = lat;
                tmpc.SegmentStart_sample = seg_start;
                tmpc.SegmentEnd_sample = seg_end;
                tmpc.SegmentStart_sec_from_VOFF = seg_start_sec;
                tmpc.SegmentEnd_sec_from_VOFF = seg_end_sec;
                tmpc.Channel = string(raw_labels{roi_idx(c)});
                tmpc.AlphaPower_raw = alpha_by_chan_raw(c);
                tmpc.AlphaPower = alpha_by_chan_out(c);
                tmpc.AlphaMetric = string(metric_name(use_log10_power));
                subject_chan_rows = [subject_chan_rows; tmpc]; %#ok<AGROW>
            end
        end

        tmpt = table();
        tmpt.File = string(filename);
        tmpt.Subject = string(nam);
        tmpt.Trial = tr;
        tmpt.Block = block_id;
        tmpt.EventType = string(voff_event);
        tmpt.VOFF_latency_sample = lat;
        tmpt.SegmentStart_sample = seg_start;
        tmpt.SegmentEnd_sample = seg_end;
        tmpt.SegmentStart_sec_from_VOFF = seg_start_sec;
        tmpt.SegmentEnd_sec_from_VOFF = seg_end_sec;
        tmpt.Fs = fs;
        tmpt.N_ROI_Channels = n_roi_chan_used;
        tmpt.AlphaPower_raw = roi_alpha_raw;
        tmpt.AlphaPower = roi_alpha;
        tmpt.AlphaMetric = string(metric_name(use_log10_power));
        tmpt.Usable = trial_usable;
        tmpt.RejectReason = reject_reason;

        subject_trial_rows = [subject_trial_rows; tmpt]; %#ok<AGROW>
    end

    fprintf('Usable VOFF alpha segments: %d / %d\n', ...
        sum(subject_trial_rows.Usable), height(subject_trial_rows));

    TRIAL_ALL = [TRIAL_ALL; subject_trial_rows]; %#ok<AGROW>
    CHAN_ALL  = [CHAN_ALL; subject_chan_rows]; %#ok<AGROW>
end

%% ===================== Save trial-level CSV =====================
writetable(TRIAL_ALL, out_trial_csv);
fprintf('\nTrial-level output saved to:\n%s\n', out_trial_csv);

%% ===================== Save channel-level CSV =====================
writetable(CHAN_ALL, out_channel_csv);
fprintf('Channel-level output saved to:\n%s\n', out_channel_csv);

%% ===================== Compute and save block-level summary =====================
if isempty(TRIAL_ALL)
    warning('No trial-level rows were produced. Block-level summary not created.');
else
    Tuse = TRIAL_ALL(TRIAL_ALL.Usable & isfinite(TRIAL_ALL.AlphaPower), :);

    if isempty(Tuse)
        warning('No usable trials for block-level summary.');
        BLOCK = table();
    else
        G = findgroups(Tuse.Subject, Tuse.Block);
        subj = splitapply(@(x)x(1), Tuse.Subject, G);
        blk  = splitapply(@(x)x(1), Tuse.Block, G);
        ntr  = splitapply(@numel, Tuse.AlphaPower, G);
        alpha_mean = splitapply(@mean_omitnan, Tuse.AlphaPower, G);
        alpha_sd   = splitapply(@std_omitnan,  Tuse.AlphaPower, G);
        alpha_raw_mean = splitapply(@mean_omitnan, Tuse.AlphaPower_raw, G);

        BLOCK = table();
        BLOCK.Subject = subj;
        BLOCK.Block = blk;
        BLOCK.N_Trials = ntr;
        BLOCK.AlphaPower = alpha_mean;
        BLOCK.AlphaPower_SD = alpha_sd;
        BLOCK.AlphaPower_raw = alpha_raw_mean;
        BLOCK.AlphaMetric = repmat(string(metric_name(use_log10_power)), height(BLOCK), 1);
    end

    writetable(BLOCK, out_block_csv);
    fprintf('Block-level output saved to:\n%s\n', out_block_csv);
end

fprintf('\nAll done.\n');

%% ===================== Helper functions =====================
function s = canonical_label(x)
    if isstring(x), x = char(x); end
    if ~ischar(x), x = char(string(x)); end
    s = upper(regexprep(x, '[\s_\-]', ''));
end

function s = canonical_event_type(x)
    if ischar(x) || isstring(x)
        s = char(x);
    elseif isnumeric(x)
        s = num2str(x);
    else
        s = '';
    end
    s = upper(regexprep(strtrim(s), '\s+', ''));
end

function [alpha_raw, alpha_out] = compute_alpha_for_channels(seg, fs, alpha_band, use_log10_power, welch_window_sec, overlap_frac, nfft_min)
    % seg: channels x samples
    nchan = size(seg, 1);
    nsamp = size(seg, 2);
    alpha_raw = nan(nchan, 1);
    alpha_out = nan(nchan, 1);

    if isempty(welch_window_sec)
        win_len = nsamp;
    else
        win_len = min(nsamp, max(1, round(welch_window_sec * fs)));
    end

    win = hamming(win_len);
    noverlap = round(overlap_frac * win_len);
    noverlap = min(noverlap, win_len - 1);
    nfft = max(nfft_min, 2^nextpow2(win_len));

    for ch = 1:nchan
        x = double(seg(ch, :));
        x = x - mean(x, 'omitnan');
        x = detrend(x);

        if all(~isfinite(x)) || std(x, 'omitnan') == 0
            continue;
        end

        [pxx, f] = pwelch(x, win, noverlap, nfft, fs);
        idx = f >= alpha_band(1) & f <= alpha_band(2);

        if ~any(idx)
            continue;
        end

        % Mean PSD within alpha band; unit is approximately uV^2/Hz if EEG is in uV.
        ap = mean(pxx(idx), 'omitnan');
        alpha_raw(ch) = ap;

        if use_log10_power
            alpha_out(ch) = log10(max(ap, realmin));
        else
            alpha_out(ch) = ap;
        end
    end
end

function y = mean_omitnan(x)
    y = mean(x, 'omitnan');
end

function y = std_omitnan(x)
    y = std(x, 'omitnan');
end

function s = metric_name(use_log10_power)
    if use_log10_power
        s = 'log10_mean_PSD_8_12Hz';
    else
        s = 'mean_PSD_8_12Hz';
    end
end
